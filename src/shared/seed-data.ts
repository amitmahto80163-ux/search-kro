export function sourced<T>(
  value: T,
  sourceName: string,
  sourceUrl: string,
  lastVerified = '2025-02-10',
  confidence: ConfidenceLevel = 'official'
): SourcedField<T> {
  return {
    value,
    sourceName,
    sourceUrl,
    lastVerified,
    confidence,
  };
}

export function unverified<T>(): SourcedField<T> {
  return {
    value: null,
    sourceName: null,
    sourceUrl: null,
    lastVerified: null,
    confidence: 'unverified',
  };
}

